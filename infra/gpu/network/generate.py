def render(c):
    files = {
        "nftables/gpu-inference.nft": render_nftables(c),
        "envoy/envoy.yaml": render_envoy(c),
        "ssh/gpu-host/sshd_config.d/10-gpu-inference.conf": render_sshd_gpu(c),
        "ssh/gpu-host/sssd.conf.d/50-session-recording.conf": render_sssd_recording(c),
        "ssh/gpu-host/tlog-rec-session.conf": render_tlog(),
        "ssh/gpu-host/audit.rules.d/50-gpu-inference.rules": render_audit_rules(c),
        "ssh/bastion/sshd_config.d/10-gpu-bastion.conf": render_sshd_bastion(c),
        "ssh/admin-client/ssh_config": render_ssh_client(c),
        "gateway.env": render_gateway_env(c),
    }
    if c["kubernetes"]:
        files["kubernetes/networkpolicy.yaml"] = render_kubernetes(c)
    return files


def generate(raw, out: Path):
    files = render(load_config(raw))
    for name, text in files.items():
        p = out / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return sorted(files)


def read_config(path):
    return yaml.safe_load(Path(path).read_text())


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default=str(HERE / "config.yaml"))
    ap.add_argument("--out", default=str(HERE / "out"))
    a = ap.parse_args(argv)
    for name in generate(read_config(a.config), Path(a.out)):
        print(Path(a.out) / name)


if __name__ == "__main__":
    main()
